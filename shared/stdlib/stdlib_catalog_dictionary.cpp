#include "stdlib/stdlib_catalog_internal.hpp"

namespace luma::stdlib::detail {

void register_dictionary_functions(std::vector<FunctionSpec>& specs, const ModuleBuilder& m,
                                   const ParamShorthands& p) {
    append_specs(
        specs,
        {
            m.fn("has_value", 2, "(dictionary: dictionary<V>, value: V)", R::boolean_type(),
                 {p.dict_any, p.any}),
            m.fn("deep_merge", 2, "(a: dictionary<V>, b: dictionary<V>)", R::dict_any(),
                 {p.dict_any, p.dict_any}),
            m.fn("each", 2, "(dictionary: dictionary<V>, f: func(string, V) -> void)",
                 R::result(R::none_type()), {p.dict_any, p.func}),
            m.fn("filter", 2, "(dictionary: dictionary<V>, f: func(string, V) -> boolean)",
                 R::result(R::dict(R::any_type())), {p.dict_any, p.func}),
            m.fn("from_entries", 1, "(pairs: array<(string, V)>)", R::dict_any(), {p.array_any}),
            m.fn("from_keys", 2, "(keys: array<string>, value: V)", R::dict_any(),
                 {p.array_string, p.any}),
            m.fn("get", 2, "(dictionary: dictionary<V>, key: string)", R::result_any(),
                 {p.dict_any, p.string}),
            m.fn("get_or", 3, "(dictionary: dictionary<V>, key: string, default: V)", R::any_type(),
                 {p.dict_any, p.string, p.any}),
            m.fn("has", 2, "(dictionary: dictionary<V>, key: string)", R::boolean_type(),
                 {p.dict_any, p.string}),
            m.fn("invert", 1, "(dictionary: dictionary<V>)", R::dict_any(), {p.dict_any}),
            m.fn("is_empty", 1, "(dictionary: dictionary<V>)", R::boolean_type(), {p.dict_any}),
            m.fn("keys", 1, "(dictionary: dictionary<V>)", R::array_string(), {p.dict_any}),
            m.fn("length", 1, "(dictionary: dictionary<V>)", R::integer_type(), {p.dict_any}),
            m.fn("map", 2, "(dictionary: dictionary<V>, f: func(string, V) -> V)",
                 R::result(R::dict(R::any_type())), {p.dict_any, p.func}),
            m.fn("map_values", 2, "(dictionary: dictionary<V>, f: func(V) -> U)",
                 R::result(R::dict(R::any_type())), {p.dict_any, p.func}),
            m.fn("merge", 2, "(a: dictionary<V>, b: dictionary<V>)", R::dict_any(),
                 {p.dict_any, p.dict_any}),
            m.fn("merge_with", 3, "(a: dictionary<V>, b: dictionary<V>, f: func(V, V) -> V)",
                 R::dict_any(), {p.dict_any, p.dict_any, p.func}),
            m.fn("partition", 2, "(dictionary: dictionary<V>, f: func(string, V) -> boolean)",
                 R::result_any(), {p.dict_any, p.func}),
            m.fn("reduce", 3, "(dictionary: dictionary<V>, initial: U, f: func(U, string, V) -> U)",
                 R::result_any(), {p.dict_any, p.any, p.func}),
            m.fn("remove", 2, "(dictionary: dictionary<V>, key: string)", R::dict_any(),
                 {p.dict_any, p.string}),
            m.fn("set", 3, "(dictionary: dictionary<V>, key: string, value: V)", R::dict_any(),
                 {p.dict_any, p.string, p.any}),
            m.fn("to_array", 1, "(dictionary: dictionary<V>)", R::array(named::key_value()),
                 {p.dict_any}),
            m.fn("to_entries", 1, "(dictionary: dictionary<V>)", R::array_any(), {p.dict_any}),
            m.fn("update", 3,
                 "(dictionary: dictionary<V>, key: string, updater: func(optional<V>) -> V)",
                 R::dict_any(), {p.dict_any, p.string, p.func}),
            m.fn("values", 1, "(dictionary: dictionary<V>)", R::array_any(), {p.dict_any}),
            m.fn("pick", 2, "(dictionary: dictionary<V>, keys: array<string>)", R::dict_any(),
                 {p.dict_any, p.array_string}),
            m.fn("omit", 2, "(dictionary: dictionary<V>, keys: array<string>)", R::dict_any(),
                 {p.dict_any, p.array_string}),
            m.fn("find", 2, "(dictionary: dictionary<V>, f: func(string, V) -> boolean)",
                 R::result_any(), {p.dict_any, p.func}),
            m.fn("flip", 1, "(dictionary: dictionary<V>)", R::result(R::dict(R::string_type())),
                 {p.dict_any}),
            m.fn("count", 2, "(dictionary: dictionary<V>, f: func(string, V) -> boolean)",
                 R::result_integer(), {p.dict_any, p.func}),
            m.fn("any", 2, "(dictionary: dictionary<V>, f: func(string, V) -> boolean)",
                 R::result_boolean(), {p.dict_any, p.func}),
            m.fn("all", 2, "(dictionary: dictionary<V>, f: func(string, V) -> boolean)",
                 R::result_boolean(), {p.dict_any, p.func}),
            m.fn("map_keys", 2, "(dictionary: dictionary<V>, f: func(string) -> string)",
                 R::result(R::dict(R::any_type())), {p.dict_any, p.func}),
            m.fn("from_arrays", 2, "(keys: array<string>, values: array<V>)",
                 R::result(R::dict(R::any_type())), {p.array_string, p.array_any}),
        });
}

} // namespace luma::stdlib::detail
